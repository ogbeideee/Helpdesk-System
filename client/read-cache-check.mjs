import assert from 'node:assert/strict';
import { createReadCache } from './src/readCache.js';
import { PAGE_SIZE, fromQuery, queuePath } from './src/ticketQueueView.js';
const deferred = () => { let resolve, reject; const promise = new Promise((a, b) => { resolve = a; reject = b; }); return { promise, resolve, reject }; };
const tick = () => new Promise(resolve => setImmediate(resolve));
let clock = 0;
const calls = [], updates = [], statuses = [];
const cache = createReadCache({ now: () => clock, ttl: 10, maxAge: 100, maxEntries: 2,
  fetcher: key => { const task = deferred(); calls.push({ key, ...task }); return task.promise; },
  onUpdate: key => updates.push(key), onStatus: status => statuses.push(status),
});
const first = cache.read('/dashboard');
const second = cache.read('/dashboard');
await tick();
assert.equal(calls.length, 1, 'overlapping requests share one fetch');
calls[0].resolve({ count: 1 });
assert.deepEqual(await first, await second);
const changed = await cache.read('/dashboard'); changed.count = 900;
assert.equal(cache.peek('/dashboard').count, 1, 'callers cannot mutate the cached result');
assert.equal(calls.length, 1, 'fresh navigation avoids another fetch');
clock = 11;
assert.equal((await cache.read('/dashboard')).count, 1, 'stale navigation renders immediately');
await tick();
assert.equal(calls.length, 2);
calls[1].resolve({ count: 2 });
await tick();
assert.deepEqual(updates, ['/dashboard']);
assert.equal(cache.peek('/dashboard').count, 2);
clock = 22;
assert.equal((await cache.read('/dashboard')).count, 2);
await tick(); calls[2].reject(new Error('Offline')); await tick();
assert.equal(cache.peek('/dashboard').count, 2, 'refresh failure keeps the last successful display');
assert(statuses.some(status => status.error), 'refresh failure is surfaced');
cache.clear();
const old = cache.read('/tickets/1'); await tick();
const oldCall = calls.at(-1);
cache.clear();
assert.equal(cache.peek('/dashboard'), null, 'session/mutation invalidation clears all records');
const fresh = cache.read('/tickets/1'); await tick();
const newCall = calls.at(-1);
oldCall.resolve({ state: 'NEW' }); newCall.resolve({ state: 'CLOSED' });
assert.equal((await old).state, 'CLOSED', 'an in-flight pre-mutation response cannot overwrite the newer state');
assert.equal((await fresh).state, 'CLOSED');
assert.equal(cache.peek('/tickets/1').state, 'CLOSED');
clock = 200;
assert.equal(cache.peek('/tickets/1'), null, 'old records expire even when left untouched');
const expired = cache.read('/tickets/1'); await tick(); calls.at(-1).resolve({ state: 'CLOSED' }); await expired;
for (const key of ['/agents', '/reports']) { const read = cache.read(key); await tick(); calls.at(-1).resolve({ key }); await read; }
assert.equal(cache.peek('/tickets/1'), null, 'cache size is bounded');
assert.equal(PAGE_SIZE, 25);
assert.deepEqual(fromQuery({ status: 'NEW', q: 'ignored', agentId: 'unassigned' }), { view: '', status: 'NEW', priority: '', category: '', group: '', agentId: 'unassigned' });
assert.equal(queuePath({ status: '', page: 2, sort: 'priority', direction: 'asc' }), '/tickets/queue?page=2&sort=priority&direction=asc');
console.log('Read cache passed: deduplication, immediate cache hits, refresh updates/failures, mutation races, expiry, session clearing and bounded memory. Queue query checks passed.');
cache.clear();
const unaffected = cache.read('/groups'); await tick(); calls.at(-1).resolve({ stable: true }); await unaffected;
const raced = cache.read('/tickets/1'); await tick(); const stale = calls.at(-1);
cache.invalidate(key => key === '/tickets/1');
assert.equal(cache.peek('/groups').stable, true, 'targeted invalidation preserves unrelated data');
const replacement = cache.read('/tickets/1'); await tick(); const latest = calls.at(-1);
stale.resolve({ state: 'NEW' }); latest.resolve({ state: 'RESOLVED' });
assert.equal((await raced).state, 'RESOLVED', 'targeted invalidation fences in-flight stale responses');
assert.equal((await replacement).state, 'RESOLVED');
