import assert from 'node:assert/strict';
import { readDraft, saveDraft, draftKey } from './src/draftView.js';
import { ticketPropertyChanges } from './src/ticketPropertiesView.js';
const rows = new Map();
const store = { getItem: key => rows.get(key), setItem: (key, value) => rows.set(key, value), removeItem: key => rows.delete(key) };
const key = draftKey(1, 9), now = Date.now();
const draft = { mode: 'internal', public: 'Reply with trailing spaces  ', internal: 'Private note' };
assert(saveDraft(store, key, draft, now));
assert.deepEqual(readDraft(store, key, now), draft);
assert.equal(readDraft(store, draftKey(2, 9), now).internal, '');
assert.equal(readDraft(store, draftKey(1, 10), now).public, '');
assert.equal(readDraft(store, key, now + 13 * 3600000).internal, '');
assert(!rows.has(key), 'expired drafts are removed');
assert.equal(saveDraft(null, key, draft), false);
assert.equal(readDraft(null, key).public, '');
store.setItem(key, '{broken'); assert.equal(readDraft(store, key).public, '');
saveDraft(store, key, draft); saveDraft(store, key, { public: '', internal: '', mode: 'public' });
assert(!rows.has(key), 'sent/discarded text is removed');
console.log('Draft checks passed: account/ticket/visibility isolation, whitespace, expiry, blocked storage and cleanup.');
const ticket = { priority: 'high', category: 'Hardware', team: { key: 'hardware' } };
assert.deepEqual(ticketPropertyChanges(ticket, { priority: 'moderate', category: 'Hardware', group: 'hardware' }, true), { priority: 'moderate' }, 'saving priority must not invoke assignment routing');
assert.deepEqual(ticketPropertyChanges(ticket, { priority: 'high', category: 'Hardware', group: '' }, true), { assignmentGroup: null });
assert.deepEqual(ticketPropertyChanges(ticket, { priority: 'high', category: 'Hardware', group: '' }, false), {}, 'non-admin forms cannot include a group change');
