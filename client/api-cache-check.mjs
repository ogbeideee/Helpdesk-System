import assert from 'node:assert/strict';
import { queuePath } from './src/ticketQueueView.js';
const storage = new Map([['td_token', 'session-one']]);
globalThis.localStorage = { getItem: key => storage.get(key) || null, setItem: (key, value) => storage.set(key, value), removeItem: key => storage.delete(key) };
globalThis.sessionStorage = { removeItem() {} };
globalThis.window = new EventTarget();
window.location = { reload() {} };
globalThis.CustomEvent = class extends Event { constructor(name, options = {}) { super(name); this.detail = options.detail; } };
const requests = [];
globalThis.fetch = async (url, options) => {
  requests.push({ url, ...options });
  return { status: 200, ok: true, json: async () => ({ url, revision: requests.length }) };
};
const { api, peekRead, setToken } = await import('./src/api.js');
await Promise.all([api.dashboard(), api.dashboard()]);
assert.equal(requests.length, 1);
await api.dashboard(); assert.equal(requests.length, 1);
assert(peekRead('/dashboard'));
await api.updateTicket(1, { priority: 'high' });
assert.equal(peekRead('/dashboard'), null, 'writes invalidate unrelated dependent views too');
await api.dashboard();
setToken('session-two');
assert.equal(peekRead('/dashboard'), null, 'account changes cannot reuse another account’s cached data');
await api.dashboard();
assert.equal(requests.at(-1).headers.Authorization, 'Bearer session-two');
setToken('cookie-session:browser-account-one');
await api.dashboard(); assert.equal(requests.at(-1).headers.Authorization, undefined, 'cookie sessions never manufacture a bearer header');
setToken('cookie-session:browser-account-two'); assert.equal(peekRead('/dashboard'), null, 'account markers differ so cache/session events cannot cross accounts');
for (const call of [() => api.me(), () => api.ticketStatus('test'), () => api.assignmentCandidates(1), () => api.availabilityPreview(), () => api.notifications()]) {
  const before = requests.length; await call(); await call();
  assert.equal(requests.length - before, 2, 'session, public, live notifications and decision reads bypass the display cache');
}
await api.listTickets({ q: 'request body', limit: 6 });
assert(requests.at(-1).url.includes('summary=1'));
await api.dashboard();
await Promise.all([api.groups(), api.getTicket(1), api.getTicket(2), api.ticketQueue()]);
assert(peekRead(queuePath({})), 'queue is populated before checking invalidation');
await api.markConversationRead(1, new Date().toISOString());
assert(peekRead('/dashboard'), 'read receipts retain dashboard data');
assert(peekRead('/assignment-groups'), 'read receipts retain reference data');
assert(peekRead('/tickets/2?history=recent'), 'read receipts retain other tickets');
assert.equal(peekRead('/tickets/1?history=recent'), null);
assert.equal(peekRead(queuePath({})), null, 'read receipts invalidate queue unread badges');
await api.updateTicket(1, { priority: 'high' });
assert.equal(peekRead('/dashboard'), null, 'ticket edits invalidate dependent counts');
assert(peekRead('/assignment-groups'), 'ticket edits retain reference data');
assert(peekRead('/tickets/2?history=recent'), 'ticket edits retain other details');
await api.moveThreadReply(1, 10, { targetTicketNumber: 'BENCH-2' });
assert.equal(peekRead('/tickets/2?history=recent'), null, 'moving a reply invalidates destination details too');
await api.groups();
await api.updateSlaSettings({});
assert.equal(peekRead('/assignment-groups'), null, 'unclassified writes retain conservative invalidation');
await api.dashboard();
window.dispatchEvent(new CustomEvent('td:changed'));
assert(peekRead('/dashboard'), 'change signal refreshes views without undoing selective write invalidation');
await api.logout();
assert.equal(storage.get('td_token'), undefined);
assert.equal(peekRead('/dashboard'), null);
console.log('API cache passed: authenticated reuse, write/account/logout invalidation, decision/public/session bypass and lightweight body search.');

